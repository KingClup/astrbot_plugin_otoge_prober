"""/sdvx 理论、/geki 理论：曲库里每张谱面都满分时的成绩图（v3.0.6）。"""
import asyncio
import io
import os
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]


def _sb(tmp_path):
    from scorebook.service import ScoreBook
    return ScoreBook(str(tmp_path))


def test_theory_scores_cover_every_chart(tmp_path):
    from scorebook import calc as K
    sb = _sb(tmp_path)
    sd = sb.theory_scores("sdvx")
    assert len(sd) == len(sb.cat("sdvx").charts) and all(v == {"s": 10_000_000, "l": "PUC"} for v in sd.values())
    rows = K.sdvx_rows(sb.cat("sdvx"), sd)
    top = rows[:50]
    assert len(top) == 50 and all(r.lamp == "PUC" and r.score == 10_000_000 for r in top)
    assert top[0].vf >= top[-1].vf and top[0].num >= 20            # 最高的一定是等级最高的那批
    gk = sb.theory_scores("geki")
    best = K.geki_best(sb.cat("geki"), gk, "理论 Rating")
    assert len(best.new) == 10 and len(best.best) == 50 and len(best.plat) == 50
    assert all(c.score == K.GEKI_MAX and c.ab and c.fb for c in (*best.new, *best.best))
    assert (best.calc or 0) > 20_000                               # Re:Fresh 理论值在 20 以上
    # 没动任何人的成绩
    assert not sb.store.has_any("someone", "sdvx") and not sb.store.has_any("someone", "geki")


def test_sdvx_theory_image_and_text(tmp_path):
    sb = _sb(tmp_path)
    img = asyncio.run(sb.sdvx_image("nobody", "", "Bot", theory=True))
    im = Image.open(io.BytesIO(img))
    assert im.width > 1000 and im.height > 1500
    t = sb.sdvx_theory_text()
    assert "理论 VOLFORCE" in t and "PUC" in t and "#20 " in t
    assert asyncio.run(sb.sdvx_image("nobody", "x", "Bot")) is None     # 没传过成绩的人，普通 b50 还是没图


def test_geki_theory_renders(tmp_path):
    from ongeki.b50img import render
    from scorebook import calc as K
    sb = _sb(tmp_path)
    best = K.geki_best(sb.cat("geki"), sb.theory_scores("geki"), "理论 Rating")
    out = tmp_path / "g.jpg"
    render(best, out, jackets={}, footer_left="Generated by Bot", region_label="理论值 · Re:Fresh 规则")
    im = Image.open(out)
    assert im.width > 1000 and im.height > 1500


def test_main_routes_theory_before_record_words():
    s = (ROOT / "main.py").read_text(encoding="utf-8")
    a = s.index('if game in ("sdvx", "geki") and first in THEORY_WORDS:')
    b = s.index("r = await sb.handle(ctx, game, first, rest)")
    assert a < b
    assert "async def _scorebook_theory" in s and 'region_label="理论值 · Re:Fresh 规则"' in s
