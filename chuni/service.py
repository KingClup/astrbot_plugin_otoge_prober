    async def lx_bearer(self, qq: str) -> str:
        """个人密钥（解密）或 OAuth access_token（自动续期）。"""
        if (self.cn.get(qq) or {}).get("source") == "lxoauth":
            try:
                from ..core.lxoauth import OAuthExpired
            except ImportError:
                from core.lxoauth import OAuthExpired
            if self.lx_oauth is None:
                raise ChuniError("落雪授权没有启用（bot 主人没配置 OAuth 应用）")
            try:
                return await self.lx_oauth.access(qq)
            except OAuthExpired as e:
                raise ChuniError(f"{e}。发「/网页绑定」→ 国服 → 落雪授权，重新点一下授权") from e
        return self._lx_token(qq)

    async def bind_cn_qq(self, qq: str) -> Profile:
        """开发者令牌按 QQ 找落雪账号，找到就记下（不存密钥）。"""
        try:
            from ..core import lxns as LX
        except ImportError:
            from core import lxns as LX
        try:
            prof = lx_profile(await LX.player_by_qq("chunithm", qq, self.lx_dev, transport=self.lx_transport,
                                                    proxy=self.settings.proxy))
        except LX.LxnsError as e:
            raise ChuniError(f"落雪查分器：{e}") from e
        self.cn.set(qq, {"source": "lxqq", "qq": str(qq), "friend_code": prof.friend_code or ""}, prof.name)
        self._cache.pop((qq, "cn_b50"), None)
        return prof

    async def _b50_lxqq(self, qq: str) -> tuple[Profile, B50]:
        """落雪开发者 API：落雪算好的 B30 + N20（selections 是候补，不进榜）。"""
        import asyncio
        try:
            from ..core import lxns as LX
        except ImportError:
            from core import lxns as LX
        if not self.lx_dev:
            raise ChuniError("bot 主人还没配置落雪开发者令牌；可以私聊「/chu 绑定 落雪 <个人API密钥>」")
        b = self.cn.get(qq) or {}
        kw = {"transport": self.lx_transport, "proxy": self.settings.proxy}
        try:
            fc = b.get("friend_code")
            if not fc:
                fc = (await LX.player_by_qq("chunithm", qq, self.lx_dev, **kw)).get("friend_code")
            pdata, best, _ok = await asyncio.gather(LX.dev_player("chunithm", fc, self.lx_dev, **kw),
                                                    LX.dev_bests("chunithm", fc, self.lx_dev, **kw),
                                                    self.lx_songs.ensure())
        except LX.LxnsError as e:
            raise ChuniError(f"落雪查分器：{e}") from e

        def conv(rows):
            out = []
            for r in rows or []:
                sc = lx_score(r)
                if sc is None:
                    continue
                hit = self.lx_songs.get(sc.song_id or 0, "", int(sc.difficulty))
                if hit and hit[0]:
                    sc.const = hit[0]
                elif (v := self.consts.cn.get((sc.song_id, sc.difficulty))) is not None:
                    sc.const = v
                out.append(sc)
            return out
        prof = lx_profile(pdata)
        res = B50(best=conv(best.get("bests")), new=conv(best.get("new_bests")), displayed_rating=prof.rating)
        res.best, res.new = res.best[:30], res.new[:20]
        return prof, res

    def _lx_token(self, qq: str) -> str:
        b = self.cn.get(qq) or {}
        enc = b.get("token_enc") or ""
        if not enc:
            return ""
        try:
            return self.store._fernet.decrypt(enc.encode()).decode()
        except Exception:  # noqa: BLE001
            return ""

