    def cn_uploaded_at(self, qq: str) -> str:
        """国服（落雪）上次上传时间（ISO）：看 b50 缓存，或 /chu 更新 单独拉资料时记下的；水鱼 / 没查过 → ''。"""
        hit = self._cache.get((qq, "cn_b50"))
        seen = self.__dict__.setdefault("_cn_upload_seen", {})
        return (getattr(hit[1][0], "uploaded_at", "") if hit else "") or seen.get(qq, "")

    def remember_cn_uploaded(self, qq: str, iso: str) -> None:
        self.__dict__.setdefault("_cn_upload_seen", {})[qq] = iso

    async def b50_cn(self, qq: str, force: bool = False) -> tuple[Profile, B50]:
        binding = self.cn.get(qq)
        if not binding and self.lx_dev and str(qq).isdigit():
            miss = self.__dict__.setdefault("_qq_miss", {})
            hit = miss.get(qq)
            if hit and time.time() - hit[0] < 600:      # 10 分钟内找过没找到：别每次都去问落雪
                raise ChuniError(hit[1])
            try:                # 没绑过国服：先按 QQ 去落雪找
                await self.bind_cn_qq(qq)
                binding = self.cn.get(qq)
                miss.pop(qq, None)
            except ChuniError as e:
                why = (f"按 QQ 在落雪没找到你（{e}）。\n你还没绑定中二国服：发「/网页绑定」，"
                       "或「/chu 绑定 国服 <水鱼用户名>」")
                miss[qq] = (time.time(), why)
                raise ChuniError(why) from e
        if not binding:
            raise ChuniError("你还没绑定中二国服，发「/chu 绑定 国服 <水鱼用户名>」或私聊「/chu 绑定 落雪 <个人API密钥>」")
        now = time.time()
        hit = self._cache.get((qq, "cn_b50"))
        if hit and not force and now - hit[0] < self.settings.scores_ttl:
            return hit[1]
        if binding.get("source") in ("lx", "lxqq", "lxoauth"):
            res = await (self._b50_lxqq(qq) if binding.get("source") == "lxqq" else self._b50_lx(qq))
            self._cache[(qq, "cn_b50")] = (now, res)
            return res
        try:
            from ..core import divingfish as DF
        except ImportError:
            from core import divingfish as DF
        try:
            data = await DF.chu_player(binding, transport=self.df_transport)
        except DF.DivingFishError as e:
            raise ChuniError(f"水鱼查分器：{e}") from e
        rec = data.get("records") or {}
        best = [df_score(r) for r in rec.get("b30") or []]
        recent = [df_score(r) for r in rec.get("r10") or []]
        prof = df_profile(data)
        res = (prof, B50(best=best, new=recent, displayed_rating=prof.rating))
        self._cache[(qq, "cn_b50")] = (now, res)
        return res

    async def cn_scores_lx(self, qq: str) -> tuple[Profile, list[Score]]:
        """落雪：资料 + 全部成绩（定数用落雪国服曲库，没有再用水鱼国服定数）。"""
        import asyncio
        try:
            from ..core import lxns as LX
        except ImportError:
            from core import lxns as LX
        token = await self.lx_bearer(qq)
        if not token:
            raise ChuniError("落雪密钥读不出来了（可能换过 secret.key），私聊重新「/chu 绑定 落雪 <密钥>」")
        try:
            pdata, raw, _ok = await asyncio.gather(
                LX.player("chunithm", token, transport=self.lx_transport, proxy=self.settings.proxy),
                LX.scores("chunithm", token, transport=self.lx_transport, proxy=self.settings.proxy),
                self.lx_songs.ensure())
        except LX.LxnsError as e:
            raise ChuniError(f"落雪查分器：{e}") from e
        out = []
        for r in raw:
            s = lx_score(r)
            if s is None:
                continue
            hit = self.lx_songs.get(s.song_id or 0, "", int(s.difficulty))
            if hit and hit[0]:
                s.const = hit[0]
            elif (v := self.consts.cn.get((s.song_id, s.difficulty))) is not None:
                s.const = v
            out.append(s)
        return lx_profile(pdata), out

    async def _b50_lx(self, qq: str) -> tuple[Profile, B50]:
        """国服按 VERSE 规则：旧曲 Best 30 + 当前版本新曲 Best 20（落雪曲库里谱面的版本 ≥ 国服当前版本算新曲）。"""
        prof, scores = await self.cn_scores_lx(qq)
        old, new = [], []
        for s in scores:
            flag = self.lx_songs.is_new(s.song_id or 0, "", int(s.difficulty))
            (new if flag else old).append(s)
        b = B50(best=old, new=new, displayed_rating=prof.rating)
        b.best, b.new = b.best[:30], b.new[:20]
        return prof, b

