    @property
    def jp_version(self) -> str | None:
        """日服当前版本（B50 logo / 新曲划分用）：进度核实给出的优先，其次日服定数表里最新的版本名。"""
        if (h := self.version_hint.get("jp")):
            return h
        from .songdb import TACHI_VERSION_NAMES
        tag = self.consts.jp_version or ""
        return TACHI_VERSION_NAMES.get(tag, tag.upper() if tag else "") or self.current_version

    def const_of(self, song: SongInfo, chart, server: str) -> float | None:
        if server == "intl":
            return chart.const if song.intl else None
        return self.consts.get(song.id, chart.difficulty).get(server)

    def consts_for(self, song: SongInfo) -> dict:
        out = {}
        for d, c in song.charts.items():
            v = {"intl": c.const} if (song.intl and c.const) else {}
            v.update(self.consts.get(song.id, d))
            out[d] = v
        return out

    # ---------- 查询 ----------

    async def profile(self, qq: str, force: bool = False, server: str = "intl") -> Profile:
        return await self._cached(qq, "profile", self.settings.profile_ttl, force, lambda c: c.profile(), server)

    async def recent(self, qq: str, force: bool = False, server: str = "intl") -> list[RecentScore]:
        scores = await self._cached(qq, "recent", self.settings.profile_ttl, force, lambda c: c.recent(), server)
        await self._fill(scores, server)
        return scores

    async def b50(self, qq: str, force: bool = False, server: str = "intl") -> tuple[Profile, B50]:
        profile = await self.profile(qq, force, server)

        async def fetch(c: ChuniNetClient):
            best, new = await c.best30(), await c.new20()
            if self.settings.b50_fetch_lamps:
                await self._merge_lamps(c, best + new)
            return best, new

        best, new = await self._cached(qq, "b50", self.settings.scores_ttl, force, fetch, server)
        await self._fill(best + new, server)
        return profile, B50(best=best, new=new, displayed_rating=profile.rating)

    @staticmethod
    async def _merge_lamps(c: ChuniNetClient, scores: list[Score]) -> None:
        """rating 页面没有 FC/AJ 和通关标记：抓出现过的难度的全曲成绩页补上（参考 chuni-penguin）。"""
        diffs = sorted({s.difficulty for s in scores if s.difficulty != Difficulty.WORLDS_END})
        lamps: dict[tuple[int | None, Difficulty], Score] = {}
        for d in diffs:
            try:
                for pb in await c.scores_by_difficulty(d):
                    lamps[(pb.song_id, pb.difficulty)] = pb
            except ChuniError:
                return  # 补灯失败不影响 B50 本身
        for s in scores:
            if (pb := lamps.get((s.song_id, s.difficulty))) is not None:
                s.combo_lamp, s.clear_lamp = pb.combo_lamp, pb.clear_lamp
                if pb.rank.value > s.rank.value:
                    s.rank = pb.rank

    async def jackets_for(self, scores: list[Score]):
        try:
            ids = [s.song_id for s in scores if s.song_id is not None]
            fb = {}
            for i in ids:
                info = self.songdb.songs.get(i)
                if info is not None and info.jacket_url:
                    fb[i] = info.jacket_url
            return await self.jackets.get_many(ids, fb)
        except Exception:  # noqa: BLE001
            return {}

    @property
    def current_version(self) -> str | None:
        """B50 主题用的版本：配置里指定了就用指定的，否则用曲库推断的当前国际服版本。"""
        tv = (self.settings.theme_version or "auto").strip()
        if tv.lower() != "auto":
            return tv
        return self.version_hint.get("intl") or self.songdb.current_version

    async def refresh_data(self) -> dict[str, object]:
        """定时任务：强制刷新曲库 + 曲绘索引。"""
        import time as _t

        result: dict[str, object] = {"at": int(_t.time())}
        try:
            await self.songdb.ensure_loaded(force=True)
            result["songdb"] = f"{self.songdb.source}，{len(self.songdb.songs)} 首"
            result["version"] = self.current_version
        except Exception as e:  # noqa: BLE001
            result["songdb"] = f"失败：{e}"
        try:
            await self.consts.ensure_loaded(force=True)
            result["consts"] = f"日服 {len(self.consts.jp)} / 国服 {len(self.consts.cn)} 张谱面定数"
        except Exception as e:  # noqa: BLE001
            result["consts"] = f"失败：{e}"
        try:
            await self.jackets.ensure_index(force=True)
            result["jackets"] = f"{len(self.jackets.index)} 首有曲绘"
        except Exception as e:  # noqa: BLE001
            result["jackets"] = f"失败：{e}"
        if self.settings.auto_logo:
            try:
                got = await self.theme.auto_logo(self.current_version)
                if got is not None:
                    result["logo"] = f"已自动获取 {self.current_version} 的 logo"
            except Exception as e:  # noqa: BLE001
                result["logo"] = f"自动获取 logo 失败：{e}"
        self.last_refresh = result
        return result

    async def song(self, qq: str, query: str, server: str = "intl") -> tuple[SongInfo, list[Score]] | list[SongInfo]:
        """唯一匹配时返回 (曲目, 成绩)；否则返回候选列表。"""
        await self.songdb.ensure_loaded()
        hits = self.songdb.search(query)
        if len(hits) != 1:
            exact = [h for h in hits if h.title == query]
            if len(exact) != 1:
                return hits
            hits = exact
        song = hits[0]
        scores = await self._cached(qq, f"song:{song.id}", self.settings.profile_ttl, False,
                                    lambda c: c.music_detail(song.id), server)
        for s in scores:
            if (ch := song.charts.get(s.difficulty)) is not None:
                s.const, s.level = ch.const, ch.level
            if server == "jp" and (v := self.consts.jp.get((song.id, s.difficulty))) is not None:
                s.const = v
        return song, scores

    async def _fill(self, scores: list[Score], server: str = "intl") -> None:
        try:
            await self.songdb.ensure_loaded()
        except Exception:  # noqa: BLE001  曲库不可用时只是没有定数
            return
        for s in scores:
            self.songdb.fill(s)
            if server == "jp" and s.song_id is not None:
                if (v := self.consts.jp.get((s.song_id, s.difficulty))) is not None:
                    s.const = v          # 日服定数（国际服曲库里的是国际服的值）
