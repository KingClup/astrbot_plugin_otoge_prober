    def priv_bound(self, qq: str) -> list[str]:
        if self.priv is None:
            return []
        try:
            from ..core.privsrv import supports
        except ImportError:
            from core.privsrv import supports
        return [s for s in self.priv.bindings.bound(qq) if supports(s, "chu")]

    async def priv_profile(self, server: str, username: str):
        """绑定前验证用户名：→ core.privsrv 的 PrivProfile。"""
        prof, _privacy = await self._priv_client(server).profile(username, "chusan")
        return prof

    async def b50_priv(self, qq: str, server: str, force: bool = False) -> tuple[Profile, B50]:
        """私服给好的旧曲 B30 + 新曲 N20 和定数（和私服网站显示的 rating 一致）。"""
        from . import privsrv as PV
        key = (qq, f"{server}:b50")
        now = time.time()
        if not force and (hit := self._cache.get(key)) and now - hit[0] < self.settings.scores_ttl:
            return hit[1]
        client = self._priv_client(server)
        pprof, best = await client.chu_best(self.priv.cred(qq, server, "chu"))
        try:
            await self.songdb.ensure_loaded()
        except Exception:  # noqa: BLE001  曲库不可用时只是歌名用私服的
            pass
        prof = PV.to_profile(pprof)
        jp = lambda mid, d: self.consts.jp.get((mid, d))  # noqa: E731  私服没给定数时用日服定数表
        b = B50(best=PV.to_scores(best.best, self.songdb, jp), new=PV.to_scores(best.new, self.songdb, jp),
                displayed_rating=prof.rating, version=PV.version_of(pprof) or None,
                rom=pprof.rom_version or "")
        self._cache[key] = (now, (prof, b))
        return prof, b

    async def recent_priv(self, qq: str, server: str):
        from . import privsrv as PV
        client = self._priv_client(server)
        _prof, plays = await client.chu_recent(self.priv.cred(qq, server, "chu"))
        try:
            await self.songdb.ensure_loaded()
        except Exception:  # noqa: BLE001
            pass

        def const_of(mid: int, diff):
            if (v := self.consts.jp.get((mid, diff))) is not None:
                return v
            song = self.songdb.songs.get(mid)
            ch = song.charts.get(diff) if song is not None else None
            return ch.const if ch is not None else None
        from zoneinfo import ZoneInfo
        try:
            tz = ZoneInfo(self.settings.timezone)
        except Exception:  # noqa: BLE001
            tz = None
        return PV.to_recent(plays, self.songdb, const_of, tz)

