def hex_(c) -> str:
    return "#%02x%02x%02x" % tuple(c[:3])


def tint(c, k=0.14):
    """浅色不透明版（半透明直接画到底图上不会混色）。"""
    return tuple(int(255 - (255 - v) * k) for v in c[:3])
