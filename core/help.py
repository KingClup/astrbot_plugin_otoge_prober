_GIRL_DIR = __import__("pathlib").Path(__file__).resolve().parent.parent / "web" / "bind" / "img"
_girls: dict = {}


def _girl(pose: str, width: int):
    """看板娘（包里没有这张图——公开版——就不画）。"""
    key = (pose, width)
    if key not in _girls:
        im = None
        try:
            from PIL import Image
            with Image.open(_GIRL_DIR / f"yume-{pose}.webp") as src:
                src = src.convert("RGBA")
                im = src.resize((width, max(1, int(src.height * width / src.width))), Image.LANCZOS)
        except (OSError, ValueError):
            im = None
        _girls[key] = im
    return _girls[key]


def _serif(d, xy, text, size, fill=NAVY) -> int:
    """宋体标题。SimSun 笔画细，描一圈同色的边当加粗。"""
    return F.draw_text(d, xy, text, "serif", size, fill, stroke=1 if size >= 26 else 0, stroke_fill=fill)


def _serif_w(text, size) -> int:
    return F.text_width(text, "serif", size) + (2 if size >= 26 else 0)


def _bg(w: int, h: int):
    """白底，顶上一片很淡的雾蓝往下化开。"""
    from PIL import Image
    im = Image.new("RGBA", (w, h), (255, 255, 255, 255))
    top = K.gradient(w, 520, [(228, 238, 250), (255, 255, 255)]).convert("RGBA")
    im.alpha_composite(top, (0, 0))
    return im


def _panel(im, box, r=22, fill=(255, 255, 255, 255)) -> None:
    """白卡片：细的雾蓝边，一点点藏青的影子。"""
    x0, y0, x1, y1 = map(int, box)
    K.shadow(im, box, r, offset=4, blur=10, alpha=22)
    ImageDraw.Draw(im).rounded_rectangle((x0, y0, x1 - 1, y1 - 1), r, fill=fill, outline=LINE, width=2)


def _footer(im, bot_name: str, M: int = 36) -> None:
    w, h = im.size
    d = ImageDraw.Draw(im)
    y = h - 70
    d.line((M, y, w - M, y), fill=NAVY, width=2)
    d.line((M, y + 6, w - M, y + 6), fill=LINE, width=1)
    text = f"Generated by {bot_name}"
    F.draw_text(d, ((w - F.text_width(text, "regular", 22)) // 2, y + 22), text, "regular", 22, EX_INK)


# ---------------------------------------------------------------- data
@dataclass
class Row:
    cmd: str                       # 指令词（带 / 的是独立指令，不带的要接在 /mai、/chu 后面）
    params: list                   # [(名字, 必填?)]
    desc: str                      # 一句话
    examples: list                 # 几个例子；详细页只显示和本页游戏对得上的
    games: tuple = ()              # 在哪些游戏里能用（单游戏页不画）


@dataclass
class Section:
    title: str
    rows: list
    note: str = ""                 # 段标题旁的小字


@dataclass
class Topic:
    key: str
    title: str
    colour: tuple
    intro: str                     # 标题下一行
    sections: list
    tips: list = field(default_factory=list)
    multi: bool = False            # 卡片上要不要画游戏标签


def R(cmd, params, desc, examples, games=()):
    if isinstance(examples, str):
        examples = [examples]
    return Row(cmd, [(p.strip("<>[]"), p.startswith("<")) for p in params], desc, list(examples), tuple(games))


