def _title(im, d, y, colour, title, sub, right_pills=(), legend=True, pose="think") -> int:
    """页头：没有卡片，直接在底上写——宋体大标题、一行说明、游戏小牌，右边看板娘；下面一粗一细两条线。"""
    base = y + TITLE_H - 8                       # 双线的位置
    girl = _girl(pose, 300)
    gw = 0
    if girl is not None:
        gw = girl.width + 10
        vis = min(girl.height, base - 6)         # 贴着线站，高出页头的部分裁掉
        im.alpha_composite(girl.crop((0, 0, girl.width, vis)), (W - M - girl.width - 6, base - vis))
        d = ImageDraw.Draw(im)
    d.rounded_rectangle((M + 4, y + 22, M + 14, y + 86), 5, fill=colour)
    size = 60
    while size > 40 and _serif_w(title, size) > W - 2 * M - gw - 60:
        size -= 2
    _serif(d, (M + 36, y + 14 + (60 - size) // 2), title, size)
    F.draw_text(d, (M + 38, y + 100), F.fit(sub, "regular", 24, W - 2 * M - gw - 60), "regular", 24, TEXT)
    px = M + 36
    for label, col in right_pills:
        px = K.pill(d, px, y + 148, label, size=19, h=32, pad=13, fg=(255, 255, 255), bg=col) + 8
    for label, col in ((("<必填>", REQ), ("[可选]", OPT)) if legend else ()):
        px = K.pill(d, px + (10 if right_pills and label == "<必填>" else 0), y + 148, label, size=19, h=32, pad=12,
                    fg=col, bg=tint(col, 0.16)) + 8
    d.line((M, base, W - M, base), fill=NAVY, width=3)
    d.line((M, base + 8, W - M, base + 8), fill=MIST, width=1)
    return y + TITLE_H


def _compose(bot_name: str, assets, blocks, colour, title, sub, right_pills=(), legend=True, pose="think") -> bytes:
    H = 30 + TITLE_H + 24 + sum(h + 22 for h, _f in blocks) + 90
    im = _bg(W, H)
    d = ImageDraw.Draw(im)
    y = _title(im, d, 30, colour, title, sub, right_pills, legend, pose) + 24
    for h, f in blocks:
        f(im, d, y)
        y += h + 22
    _footer(im, bot_name)
    return K.to_png(im)


